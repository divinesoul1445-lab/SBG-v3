    def print_scene_durations(
        self,
        audio_files,
    ):

        scene_data = (
            self.get_scene_durations(
                audio_files
            )
        )

        print()

        print(
            f"{'Scene':<8}"
            f"{'Narration':>14}"
            f"{'Image duration':>20}"
        )

