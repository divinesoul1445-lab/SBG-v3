    # ==========================================================
    # AUDIO DURATION
    # ==========================================================

    def _audio_duration(
        self,
        audio_file: Path,
    ) -> float:

        audio_file = Path(
            audio_file
        )

        command = [

            self.ffprobe,
            "-hide_banner",
            "-loglevel", "error",
            "-v",
            "error",

            "-show_entries",
            "format=duration",

            "-of",
            "default="
            "noprint_wrappers=1:"
            "nokey=1",

            str(audio_file),
        ]

        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            check=True,
        )

        value = (
            result.stdout
            .strip()
        )

        if not value:

            raise Exception(
                f"Could not determine audio duration:\n"
                f"{audio_file}"
            )

        duration = float(
            value
        )

        if duration <= 0:

            raise Exception(
                f"Audio has zero duration:\n"
                f"{audio_file}"
            )

        return duration

    # ==========================================================
    # Video DURATION
    # ==========================================================

    def _video_duration(
        self,
        video_file,
    ):
        """
        Return the exact duration of a video file in seconds.

        Uses FFprobe so the duration comes from the actual
        rendered scene video.
        """

        video_file = Path(
            video_file
        )

        if not video_file.exists():
            raise FileNotFoundError(
                f"Video file not found:\n"
                f"{video_file}"
            )

        command = [
            self.ffprobe,
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(video_file),
        ]

        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            check=True,
        )

        duration_text = (
            result.stdout.strip()
        )

        if not duration_text:
            raise RuntimeError(
                f"FFprobe returned no duration for:\n"
                f"{video_file}"
            )

        duration = float(
            duration_text
        )

        if duration <= 0:
            raise RuntimeError(
                f"Invalid video duration "
                f"{duration:.6f}s:\n"
                f"{video_file}"
            )

        return duration


    # ==========================================================
    # CHECK FILE
    # ==========================================================

    def _check_file(
        self,
        file_path,
        description,
    ):

        file_path = Path(
            file_path
        )

        if not file_path.exists():

            raise FileNotFoundError(
                f"{description} not found:\n"
                f"{file_path}"
            )

        if file_path.stat().st_size <= 0:

            raise Exception(
                f"{description} is empty:\n"
                f"{file_path}"
            )

        return file_path

    # ==========================================================
    # ESCAPE FILTER PATH
    # ==========================================================

    def _escape_filter_path(
        self,
        file_path,
    ):

        path = str(
            Path(
                file_path
            ).resolve()
        )

        path = path.replace(
            "\\",
            "/",
        )

        path = path.replace(
            ":",
            "\\:",
        )

        path = path.replace(
            "'",
            "\\'",
        )

        return path

